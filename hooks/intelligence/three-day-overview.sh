#!/bin/bash
# three-day-overview.sh — scheduled job (runs daily, self-throttles to ~72h)
# Aggregates last 72 hours of correction-log + intelligence digests + product health
# into a single markdown overview.
#
# Configuration (env vars):
#   GMOS_HOME              Default: ~/.god-mode-os
#   GMOS_REPORTS_DIR       Default: $GMOS_HOME/reports
#   GMOS_INTEL_DIR         Default: $GMOS_HOME/intelligence
#   GMOS_CORRECTION_LOG    Default: $GMOS_HOME/correction-log.md
#   GMOS_HEALTH_URLS       Path to health-check-urls.txt. Optional.
#   GMOS_QUESTIONS_LOG     Default: $GMOS_REPORTS_DIR/open-questions.log

export PATH="/opt/homebrew/bin:/usr/local/bin:/usr/bin:/bin:$PATH"
set -uo pipefail

GMOS_HOME="${GMOS_HOME:-$HOME/.god-mode-os}"
REPORTS_DIR="${GMOS_REPORTS_DIR:-$GMOS_HOME/reports}"
INTEL_DIR="${GMOS_INTEL_DIR:-$GMOS_HOME/intelligence}"
CORRECTION_LOG="${GMOS_CORRECTION_LOG:-$GMOS_HOME/correction-log.md}"
HEALTH_URLS="${GMOS_HEALTH_URLS:-$GMOS_HOME/health-check-urls.txt}"
QUESTIONS_LOG="${GMOS_QUESTIONS_LOG:-$REPORTS_DIR/open-questions.log}"
MARK="$GMOS_HOME/.three-day-overview.last-run"
LOG="$GMOS_HOME/three-day-overview.log"
DATE=$(date +%Y-%m-%d)
OUTPUT="$REPORTS_DIR/three-day-overview-$DATE.md"

mkdir -p "$REPORTS_DIR" "$INTEL_DIR" "$GMOS_HOME"
echo "[$(date '+%Y-%m-%d %H:%M')] start" >> "$LOG"

# Self-throttle: skip if last run < 72h ago
if [ -f "$MARK" ]; then
    LAST=$(cat "$MARK")
    NOW=$(date +%s)
    AGE=$(( NOW - LAST ))
    if [ "$AGE" -lt 259200 ]; then
        echo "[$(date '+%Y-%m-%d %H:%M')] throttled (${AGE}s)" >> "$LOG"
        exit 0
    fi
fi

INTEL_RECENT=""
if [ -d "$INTEL_DIR" ]; then
    INTEL_RECENT=$(ls -1t "$INTEL_DIR"/*.md 2>/dev/null | head -3 | while read -r f; do
        echo "### $(basename "$f" .md)"
        head -40 "$f"
        echo ""
    done)
fi

CORRECTIONS=""
if [ -f "$CORRECTION_LOG" ]; then
    CORRECTIONS=$(tail -200 "$CORRECTION_LOG" \
        | sed 's/ | Snippet:.*//' \
        | awk 'length > 0 && length < 400' \
        | tail -20)
fi

check_url() {
    local url="$1" name="$2" code
    code=$(curl -o /dev/null -s -w "%{http_code}" --max-time 8 -L "$url" 2>/dev/null || echo "000")
    if [ "$code" = "200" ] || [ "$code" = "301" ] || [ "$code" = "302" ]; then
        echo "- OK **$name** ($url) $code"
    else
        echo "- DOWN **$name** ($url) $code"
    fi
}

HEALTH=""
if [ -f "$HEALTH_URLS" ]; then
    while IFS='|' read -r url name; do
        [ -z "${url:-}" ] && continue
        [[ "$url" =~ ^# ]] && continue
        HEALTH+=$(check_url "$url" "${name:-unnamed}")$'\n'
    done < "$HEALTH_URLS"
else
    HEALTH="_No URLs configured. Create $HEALTH_URLS (see install/health-check-urls.txt.example)._"
fi

QUESTION=$(awk 'BEGIN{srand(); qs[0]="What did you plan this week but not ship? Why?"; qs[1]="If you could automate one recurring task in the next 2 hours, which?"; qs[2]="What correction above surprises you most?"; qs[3]="Which live product deserves 30 minutes of attention today?"; qs[4]="What is one decision you have been avoiding?"; print qs[int(rand()*5)]}')

cat > "$OUTPUT" <<MARKDOWN_EOF
# 3-Day Overview: $DATE

## 1. What I learned about you (last 72h)

$(echo "$CORRECTIONS" | tail -40)

## 2. Live product health

$HEALTH

## 3. Builder signals (last 3 daily digests, condensed)

$INTEL_RECENT

## 4. One question for you

$QUESTION

_(Log your answer to $QUESTIONS_LOG.)_

---

_Generated by [god-mode-os](https://github.com/Wishmakingfairy/god-mode-os) three-day-overview.sh. Next run: in ~72h. Customize feeds and health checks in \`~/.god-mode-os/\`. Built by [Harald Gabrans](https://linkedin.com/in/haraldsgabrans) ([@Wishmakingfairy](https://github.com/Wishmakingfairy))._
MARKDOWN_EOF

{
    echo "## $DATE"
    echo "Q: $QUESTION"
    echo "A: "
    echo ""
} >> "$QUESTIONS_LOG"

INBOX="$INTEL_DIR/INBOX.md"
{
    echo "## 3-day overview $DATE"
    echo "- [Open digest]($OUTPUT)"
    echo ""
} >> "$INBOX"

TN=$(command -v terminal-notifier || true)
if [ -n "$TN" ]; then
    "$TN" -title "3-day overview ready" -subtitle "$DATE" \
          -message "Click to open the digest." \
          -open "file://$OUTPUT" -sound default 2>/dev/null || true
fi

date +%s > "$MARK"
echo "[$(date '+%Y-%m-%d %H:%M')] wrote $OUTPUT" >> "$LOG"
exit 0
