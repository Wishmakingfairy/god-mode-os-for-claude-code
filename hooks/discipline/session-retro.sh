#!/bin/bash
# session-retro.sh — Stop event hook
# Auto-writes a session retrospective to docs/retros/YYYY-MM-DD-topic.md
# when the session made GMOS_RETRO_MIN_TOOLS or more tool calls (default: 5).
#
# Uses Gemini CLI for synthesis if installed; falls back to raw stats.
# Honors kill switch.

export PATH="/opt/homebrew/bin:/usr/local/bin:/usr/bin:/bin:$PATH"
set -u

GMOS_HOME="${GMOS_HOME:-$HOME/.god-mode-os}"
KILL_SWITCH="${GMOS_KILL_SWITCH:-$HOME/.claude/.god-mode-disabled}"
MIN_TOOLS="${GMOS_RETRO_MIN_TOOLS:-5}"

[ -f "$KILL_SWITCH" ] && exit 0

INPUT=$(cat)
[ -z "$INPUT" ] && exit 0
command -v jq >/dev/null 2>&1 || exit 0

STOP_ACTIVE=$(echo "$INPUT" | jq -r '.stop_hook_active // false')
[ "$STOP_ACTIVE" = "true" ] && exit 0

TRANSCRIPT_PATH=$(echo "$INPUT" | jq -r '.transcript_path // empty')
[ -z "$TRANSCRIPT_PATH" ] || [ ! -f "$TRANSCRIPT_PATH" ] && exit 0

CWD=$(echo "$INPUT" | jq -r '.cwd // empty')
[ -z "$CWD" ] && CWD="$HOME"

TOOL_COUNT=$(jq -r 'select(.message.content? != null) | .message.content[] | select(.type? == "tool_use") | .name' "$TRANSCRIPT_PATH" 2>/dev/null | wc -l | tr -d ' ')
[ "${TOOL_COUNT:-0}" -lt "$MIN_TOOLS" ] && exit 0

# Retro folder: project-local docs/retros if we are in a project, else ~/.god-mode-os/retros
if [ -d "$CWD/.git" ] || [ -f "$CWD/package.json" ] || [ -f "$CWD/CLAUDE.md" ]; then
    RETRO_DIR="$CWD/docs/retros"
else
    RETRO_DIR="$GMOS_HOME/retros"
fi
mkdir -p "$RETRO_DIR"

DATE=$(date +%Y-%m-%d)
FIRST_USER=$(jq -rs '[.[] | select((.message.role? == "user" or .role? == "user"))] | first | (.message.content? // .content? // "") | if type == "array" then (map(select(.type? == "text") | .text) | join(" ")) else tostring end' "$TRANSCRIPT_PATH" 2>/dev/null | head -c 80 | tr -cd '[:alnum:] -' | tr ' ' '-' | tr -s '-' | sed 's/-$//')
[ -z "$FIRST_USER" ] && FIRST_USER="session"
SLUG=$(echo "$FIRST_USER" | tr '[:upper:]' '[:lower:]' | cut -c1-40)
OUT="$RETRO_DIR/$DATE-$SLUG.md"

EDITS=$(jq -r 'select(.message.content? != null) | .message.content[] | select(.type? == "tool_use" and (.name == "Edit" or .name == "Write" or .name == "MultiEdit")) | .input.file_path // empty' "$TRANSCRIPT_PATH" 2>/dev/null | sort -u)
BASH_LOG=$(jq -r 'select(.message.content? != null) | .message.content[] | select(.type? == "tool_use" and .name == "Bash") | .input.description // .input.command // empty' "$TRANSCRIPT_PATH" 2>/dev/null | head -20)

RETRO_BODY=""
if command -v gemini >/dev/null 2>&1; then
    RETRO_BODY=$(jq -rs '[.[] | select((.message.role? == "assistant" or .role? == "assistant"))] | map((.message.content? // .content? // []) | if type == "array" then (map(select(.type? == "text") | .text) | join(" ")) else tostring end) | join("\n---\n")' "$TRANSCRIPT_PATH" 2>/dev/null | tail -c 40000 | gemini -p "Generate a session retro from these assistant turns. Sections: What we tried, What worked, What broke, Follow-ups, One thing to remember next session. Max 300 words. No em dashes." 2>/dev/null)
fi

cat > "$OUT" <<EOF
# Retro: $DATE. ${FIRST_USER//-/ }

**Tool calls:** $TOOL_COUNT
**Working dir:** $CWD

## Files touched
$(echo "$EDITS" | sed 's/^/- /' | head -20)

## Bash activity (first 20)
\`\`\`
$BASH_LOG
\`\`\`

## Synthesis
$RETRO_BODY

---
_Generated by god-mode-os session-retro.sh. Next session should read this for continuity._
EOF

# Append to global retro index
INDEX="$GMOS_HOME/retros/INDEX.md"
mkdir -p "$(dirname "$INDEX")"
echo "- $DATE. [${FIRST_USER//-/ }]($OUT)" >> "$INDEX"

exit 0
